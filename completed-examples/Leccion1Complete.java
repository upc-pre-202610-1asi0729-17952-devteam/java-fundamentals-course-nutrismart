public class Leccion1Complete {
    public static void main(String[] args) {
        
        // El primer programa: Hola mundo
        System.out.println("Hola mundo");

        // int: numeros enteros (sin decimales)
        int edad = 15;

        // double: numeros con decimales
        double nota = 18.5;

        // String: texto (siempre entre comillas dobles)
        String nombre = "María";

        // boolean: solo dos valores posibles - true o false
        boolean aprobado = true;

        // El + une el texto con el valor de la variable
        System.out.println("Nombre: " + nombre);
        System.out.println("Edad: " + edad);
        System.out.println("Nota: " + nota);
        System.out.println("Aprobado: " + aprobado);

    }
}
